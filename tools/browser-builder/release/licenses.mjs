import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { put, readAsset, sha256, jsonBytes } from './files.mjs';
import { zipEntries } from './archives.mjs';
import { verifyNugetPackages } from './nuget.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const xml = (text, name) => text.match(new RegExp(`<${name}(?:\\s[^>]*)?>([\\s\\S]*?)<\\/${name}>`, 'i'))?.[1]?.trim() ?? null;
const attr = (text, tag, key) => text.match(new RegExp(`<${tag}\\b[^>]*\\b${key}="([^"]+)"`, 'i'))?.[1] ?? null;
const decode = text => text?.replaceAll('&amp;', '&').replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&quot;', '"') ?? null;

export async function collectLicenses({ out, repoRoot, rewriterBundle, shaderPipelineBundle, nugetAssets, dotnetRuntimePack, scratch }) {
  const components = [], nuget = [];
  async function license(component, name, bytes, origin) {
    if (!bytes.length || bytes.toString('utf8').startsWith('Crawl failed')) throw new Error(`Missing actual license text for ${component}: ${name}`);
    const destination = 'licenses/' + name;
    await put(out, destination, bytes);
    return { path: destination, sha256: sha256(bytes), origin };
  }
  async function fileLicense(component, name, source, origin) { return license(component, name, await readFile(source), origin); }
  const nx = path.join(repoRoot, 'external/nxnative');
  const ryu = path.join(nx, 'dm/third_party/ryujinx');
  components.push({ name: 'nxnative', version: '0045c1dfb639f9775891382646ad38c2a11c56bf', license: 'MIT', files: [await fileLicense('nxnative', 'nxnative/LICENSE', path.join(nx, 'LICENSE'), 'pinned nxnative LICENSE')] });
  components.push({ name: 'Ryujinx.Common and Ryujinx.Graphics.Shader', version: 'nxnative 0045c1dfb639f9775891382646ad38c2a11c56bf', license: 'MIT', files: [await fileLicense('Ryujinx', 'ryujinx/LICENSE.txt', path.join(ryu, 'LICENSE.txt'), 'source-linked Ryujinx LICENSE.txt')] });
  const grammar = await readFile(path.join(ryu, 'src/Spv.Generator/Autogenerated/CoreGrammar.cs'), 'utf8');
  const grammarLicense = grammar.match(/#region Grammar License\s*([\s\S]*?)#endregion/)?.[1];
  if (!grammarLicense?.includes('Copyright')) throw new Error('SPIR-V grammar copyright/license header is missing');
  components.push({ name: 'Spv.Generator and Khronos SPIR-V grammar', version: 'nxnative 0045c1dfb639f9775891382646ad38c2a11c56bf', license: 'MIT and Khronos permissive terms', files: [
    await fileLicense('Spv.Generator', 'spv-generator/LICENSE', path.join(ryu, 'src/Spv.Generator/LICENSE'), 'source-linked Spv.Generator/LICENSE'),
    await license('Khronos grammar', 'spv-generator/KHRONOS-GRAMMAR.txt', Buffer.from(grammarLicense), 'CoreGrammar.cs #region Grammar License'),
  ] });
  const crossSource = JSON.parse(await readFile(path.join(repoRoot, 'tools/browser-builder/wasm/shaders/sources.json'), 'utf8')).spirvCross;
  components.push({ name: 'SPIRV-Cross', version: crossSource.revision, license: crossSource.license, files: [await fileLicense('SPIRV-Cross', 'spirv-cross/LICENSE', path.join(shaderPipelineBundle, 'cross/SPIRV-Cross.LICENSE'), 'pinned SPIRV-Cross LICENSE')] });
  const dotnetLicense = await readAsset(dotnetRuntimePack, 'LICENSE.TXT');
  components.push({ name: '.NET browser runtime', version: '10.0.13', license: 'MIT and bundled third-party terms', files: [
    await license('.NET', 'dotnet/LICENSE.TXT', dotnetLicense, 'Microsoft.NETCore.App.Runtime.Mono.browser-wasm/10.0.13/LICENSE.TXT'),
    await fileLicense('.NET', 'dotnet/THIRD-PARTY-NOTICES.TXT', path.join(dotnetRuntimePack, 'THIRD-PARTY-NOTICES.TXT'), 'runtime pack bundled notices'),
  ] });
  for (const [name, file, version, spdx] of [['CPython', 'CPYTHON-LICENSE.txt', '3.13 (Pyodide 0.28.3)', 'PSF-2.0 and included terms'], ['Pyodide', 'PYODIDE-LICENSE.txt', '0.28.3', 'MPL-2.0']]) {
    components.push({ name, version, license: spdx, files: [await fileLicense(name, 'python/' + file, path.join(rewriterBundle, 'licenses', file), 'canonical rewriter license copy')] });
  }
  for (const [name, filename, version] of [['Capstone', 'capstone-5.0.6-py3-none-pyodide_2025_0_wasm32.whl', '5.0.6'], ['python-lz4 and LZ4', 'lz4-4.4.4-cp313-cp313-pyodide_2025_0_wasm32.whl', '4.4.4']]) {
    const entries = zipEntries(await readAsset(rewriterBundle, filename));
    const notices = entries.filter(e => /(?:^|\/)(?:licen[sc]e[^/]*|copying[^/]*|notice[^/]*|copyright[^/]*)$/i.test(e.name));
    if (!notices.length) throw new Error(`Actual wheel licenses are missing: ${filename}`);
    const files = [];
    for (const entry of notices) files.push(await license(name, 'wheels/' + entry.name, entry.bytes, filename + '!/' + entry.name));
    components.push({ name, version, license: 'BSD; complete wheel license files included', files });
  }
  const origins = JSON.parse(await readFile(path.join(here, 'licenses/origins.json'), 'utf8'));
  const fallback = {};
  for (const [name, info] of Object.entries(origins)) {
    const bytes = await readFile(path.join(here, 'licenses', name + '.txt'));
    if (sha256(bytes) !== info.sha256) throw new Error(`Pinned upstream license hash mismatch: ${name}`);
    fallback[name] = { bytes, info };
  }
  const cross = components.find(c => c.name === 'SPIRV-Cross');
  for (const name of Object.keys(fallback).filter(name => name.startsWith('Cross-'))) {
    cross.files.push(await license('SPIRV-Cross', 'spirv-cross/' + name + '.txt', fallback[name].bytes, fallback[name].info.url));
  }
  cross.license = crossSource.license + '; complete upstream license catalog and header notices included';
  const emFiles = [];
  for (const name of ['Emscripten', 'Emscripten-libcxx', 'Emscripten-libcxxabi', 'Emscripten-musl', 'Emscripten-compiler-rt']) {
    if (!fallback[name]) throw new Error(`Linked WASM runtime library notice is missing: ${name}`);
    emFiles.push(await license(name, 'emscripten/' + name + '.txt', fallback[name].bytes, fallback[name].info.url));
  }
  components.push({ name: 'Emscripten runtime, libc++, libc++abi, musl and compiler-rt', version: '6.0.13', license: 'MIT, Apache-2.0 with LLVM exceptions and bundled terms', files: emFiles });
  const signing = path.join(repoRoot, 'tools/browser-builder/signing');
  const hashPackage = path.join(signing, 'node_modules/hash-wasm');
  const hashMetadata = JSON.parse(await readFile(path.join(hashPackage, 'package.json'), 'utf8'));
  const signingLock = await readFile(path.join(signing, 'bun.lock'));
  if (hashMetadata.version !== '4.12.0' || !signingLock.toString().includes('hash-wasm@4.12.0')) throw new Error('Browser resource-seal hash-wasm dependency does not match its pin');
  const hashFiles = [await fileLicense('hash-wasm', 'hash-wasm/LICENSE', path.join(hashPackage, 'LICENSE'), 'installed hash-wasm 4.12.0 LICENSE')];
  for (const name of ['sha1.c', 'sha256.c']) {
    const source = await readFile(path.join(hashPackage, 'src', name), 'utf8');
    const notice = source.match(/^\/\*[\s\S]*?\*\//)?.[0];
    if (!notice) throw new Error(`Missing actual hash-wasm implementation notice: ${name}`);
    hashFiles.push(await license('hash-wasm', 'hash-wasm/' + name + '.notice.txt', Buffer.from(notice + '\n'), 'hash-wasm 4.12.0 src/' + name + ' copyright/license header'));
  }
  components.push({ name: 'hash-wasm SHA-1/SHA-256 for browser ad-hoc resource seal', version: '4.12.0', license: 'MIT; included public-domain/SHA-256 permissive implementation notices', source: { url: hashMetadata.repository.url, signingLockSha256: sha256(signingLock), moduleSha256: sha256(await readFile(path.join(hashPackage, hashMetadata.module))) }, files: hashFiles, distribution: 'Bundled into Main-owned browser worker; no native Apple signing tool is distributed' });
  const shaderToolchain = JSON.parse(await readAsset(shaderPipelineBundle, 'toolchain.json'));
  if (shaderToolchain.lzmaWheel) {
    if (!fallback.Liblzma) throw new Error('The actual liblzma upstream licensing notice is required');
    components.push({ name: 'CPython LZMA module', version: '1.0.0 (Pyodide 0.28.3)', license: 'PSF-2.0', wheelSha256: sha256(await readAsset(shaderPipelineBundle, shaderToolchain.lzmaWheel)), files: components.find(c => c.name === 'CPython').files });
    components.push({ name: 'liblzma (XZ Utils library only)', version: '5.2.2', license: 'Public domain / BSD-0-Clause per Pyodide recipe', source: { url: 'https://github.com/tukaani-project/xz/tree/v5.2.2', archiveSha256: '73df4d5d34f0468bd57d09f2d8af363e95ed6cc3a4a86129d2f2c366259902a2' }, files: [await license('liblzma', 'lzma/COPYING', fallback.Liblzma.bytes, fallback.Liblzma.info.url)] });
  }
  const resolved = new Map();
  for (const [stage, filename] of Object.entries(nugetAssets)) {
    const assets = JSON.parse(await readFile(filename, 'utf8'));
    for (const [idVersion, library] of Object.entries(assets.libraries)) {
      if (library.type !== 'package') continue;
      const existing = resolved.get(idVersion);
      if (existing && existing.library.sha512 !== library.sha512) throw new Error(`NuGet resolution mismatch: ${idVersion}`);
      if (existing) { existing.stages.push(stage); continue; }
      let packageRoot;
      for (const folder of Object.keys(assets.packageFolders)) {
        const candidate = path.join(folder, library.path);
        try { await readdir(candidate); packageRoot = candidate; break; } catch { }
      }
      if (!packageRoot) throw new Error(`Resolved NuGet package is absent: ${idVersion}`);
      resolved.set(idVersion, { library, stages: [stage], packageRoot });
    }
  }
  const verified = await verifyNugetPackages([...resolved].map(([id, entry]) => ({ id, expectedContentHash: entry.library.sha512, file: path.join(entry.packageRoot, id.toLowerCase().replace('/', '.') + '.nupkg') })), scratch);
  for (const [idVersion, { library, stages, packageRoot }] of [...resolved].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
    const [id, version] = idVersion.split('/');
    const packageBytes = await readAsset(packageRoot, id.toLowerCase() + '.' + version + '.nupkg');
    const archiveSha512 = createHash('sha512').update(packageBytes).digest('base64');
    const cacheArchiveHash = (await readAsset(packageRoot, id.toLowerCase() + '.' + version + '.nupkg.sha512')).toString().trim();
    if (archiveSha512 !== cacheArchiveHash) throw new Error(`NuGet cached archive hash mismatch: ${idVersion}`);
    const nuspecName = library.files.find(name => name.endsWith('.nuspec'));
    if (!nuspecName) throw new Error(`NuGet metadata is missing: ${idVersion}`);
    const nuspecBytes = await readAsset(packageRoot, nuspecName), nuspec = nuspecBytes.toString('utf8');
    const metadata = { id, version, contentHash: library.sha512, archiveSha512, packageSha256: sha256(packageBytes), verification: verified.get(idVersion), stages: stages.sort(), licenseExpression: decode(xml(nuspec, 'license')), copyright: decode(xml(nuspec, 'copyright')), authors: decode(xml(nuspec, 'authors')), source: { url: attr(nuspec, 'repository', 'url') ?? decode(xml(nuspec, 'projectUrl')), revision: attr(nuspec, 'repository', 'commit') }, files: [] };
    const prefix = 'nuget/' + id + '/' + version + '/';
    await put(out, 'licenses/' + prefix + nuspecName, nuspecBytes);
    metadata.metadataPath = 'licenses/' + prefix + nuspecName;
    const notices = library.files.filter(name => /(?:^|\/)(?:licen[sc]e[^/]*|copying[^/]*|notice[^/]*|third-party-notices[^/]*|copyright[^/]*)$/i.test(name));
    for (const name of notices) metadata.files.push(await fileLicense(id, prefix + name, path.join(packageRoot, name), `${idVersion} package ${name}`));
    const actualLicense = notices.some(name => /(?:^|\/)(?:licen[sc]e|copying)/i.test(name));
    if (!actualLicense) {
      const key = /^Humanizer(?:\.|$)/i.test(id) ? 'Humanizer' : id === 'Mono.Cecil' ? 'Cecil' : id === 'Microsoft.IO.RecyclableMemoryStream' ? 'RecyclableMemoryStream' : id === 'MsgPack.Cli' ? 'MsgPack' : null;
      if (key) {
        if (!fallback[key]) throw new Error(`Actual upstream license text is missing: ${idVersion}`);
        metadata.files.push(await license(id, prefix + 'UPSTREAM-LICENSE.txt', fallback[key].bytes, fallback[key].info.url));
      } else if (/^(?:Microsoft\.|System\.)/.test(id) && metadata.licenseExpression === 'MIT') {
        metadata.files.push(await license(id, prefix + 'LICENSE.txt', dotnetLicense, '.NET runtime MIT license; package copyright preserved in .nuspec'));
      } else if (id === 'LibHac' && metadata.licenseExpression === 'MIT' && metadata.copyright) {
        const text = fallback.MIT?.bytes.toString('utf8').split('## License text\n\n')[1]?.split('\n## SPDX web page')[0];
        if (!text) throw new Error('NuGet MIT expression terms are missing');
        const terms = text.replace('Copyright (c) <year> <copyright holders>', metadata.copyright);
        metadata.files.push(await license(id, prefix + 'LICENSE.txt', Buffer.from(terms.trim() + '\n'), 'LibHac package MIT expression + exact package copyright + https://licenses.nuget.org/MIT terms'));
      } else throw new Error(`License text is unresolved for ${idVersion}; refusing publication`);
    }
    nuget.push(metadata);
  }
  const inventory = { format: 1, components, nuget, note: 'All resolved NuGet packages are inventoried conservatively; some are build-only or removed by trimming. Only browser assets are distributed.' };
  await put(out, 'dependencies.json', jsonBytes(inventory));
  await put(out, 'THIRD-PARTY-NOTICES.md', Buffer.from('# Browser tool dependency notices\n\nKeep this file, dependencies.json, source provenance and the complete licenses/ directory with the browser tools.\n\n' + components.map(c => `- ${c.name}: ${c.version}; ${c.license}. ${c.files.map(f => `[license](${f.path})`).join(' ')}`).join('\n') + '\n\nAll ' + nuget.length + ' resolved NuGet package versions, content hashes, original metadata and license/notice files are recorded in dependencies.json. The LibHac browser adaptation replaces AES factory calls with the extractor managed implementation; original package bytes are unchanged. Source changes and build recipes are supplied in sources.json. No Apple Metal compiler or native test executable is distributed.\n'));
  return inventory;
}
