import assert from 'node:assert/strict';
import { readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { assemble, repoRoot } from '../assemble.mjs';
import { defaultAssets } from '../options.mjs';
import { verifyBundle } from '../verify.mjs';
import { auditBytes } from '../audit.mjs';

const scratch = path.join(repoRoot, 'tmp/odyssey/browser-release-tools');
const tests = path.join(scratch, 'test-output');
await mkdir(tests, { recursive: true });
const assets = await defaultAssets();
const first = await assemble({ outDir: path.join(tests, 'first'), ...assets });
const repeat = await assemble({ outDir: path.join(tests, 'repeat'), ...assets });
assert.deepEqual(first, repeat, 'Identical real stages must produce deterministic manifest identities');
assert.deepEqual(await readFile(path.join(tests, 'first/manifest.json')), await readFile(path.join(tests, 'repeat/manifest.json')));
assert.deepEqual(await readFile(path.join(tests, 'first/SHA256SUMS')), await readFile(path.join(tests, 'repeat/SHA256SUMS')));
const audit = await verifyBundle(path.join(tests, 'first'));
const inventory = JSON.parse(await readFile(path.join(tests, 'first/dependencies.json'), 'utf8'));
for (const name of ['CPython', 'Pyodide', 'Capstone', 'python-lz4 and LZ4', '.NET browser runtime', 'Spv.Generator and Khronos SPIR-V grammar', 'SPIRV-Cross']) assert(inventory.components.some(row => row.name === name), name);
for (const name of ['LibHac', 'BouncyCastle.Cryptography', 'Mono.Cecil']) assert(inventory.nuget.some(row => row.id === name), name);
assert(inventory.nuget.every(row => row.verification.integrityVerified && row.files.length));
// Verify real native bytes are rejected even under a browser-looking filename.
const native = await readFile(process.execPath);
assert.throws(() => auditBytes('renamed-runtime.mjs', native), /Mach-O|ELF|native PE/);
const extractorAssets = JSON.parse(await readFile(assets.nugetAssets.extractor, 'utf8'));
const packageRoot = Object.keys(extractorAssets.packageFolders)[0];
assert.equal(auditBytes('LibHac.dll', await readFile(path.join(packageRoot, 'libhac/0.19.0/lib/net7.0/LibHac.dll'))), 'managed PE');
const before = await readFile(path.join(tests, 'first/manifest.json'));
await assert.rejects(() => assemble({ outDir: path.join(tests, 'first'), ...assets, shaderPipelineBundle: path.join(tests, 'missing-shader-stage') }), /missing/);
assert.deepEqual(await readFile(path.join(tests, 'first/manifest.json')), before, 'Failed assembly must preserve the previous complete bundle');
const stray = path.join(tests, 'first/rewriter/fixture.json');
await writeFile(stray, '{}');
await assert.rejects(() => verifyBundle(path.join(tests, 'first')), /Unexpected/);
await rm(stray);
const script = path.join(tests, 'first/rewriter/worker.mjs'), original = await readFile(script);
await writeFile(script, Buffer.concat([original, Buffer.from('\n// tampered')]));
await assert.rejects(() => verifyBundle(path.join(tests, 'first')), /checksum/);
await writeFile(script, original);
await verifyBundle(path.join(tests, 'first'));
const proof = { deterministic: true, completeLicenseInventory: true, signedNugetIntegrity: true, nativeBinaryRejected: true, managedDllAccepted: true, missingComponentPreservesOutput: true, unmanifestedFileRejected: true, tamperedAssetRejected: true, audit };
await writeFile(path.join(scratch, 'release-tests.json'), JSON.stringify(proof, null, 2) + '\n');
console.log(JSON.stringify(proof, null, 2));
