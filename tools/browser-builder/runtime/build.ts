import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRuntimeRecipe } from './recipe';

const builder = fileURLToPath(new URL('..', import.meta.url));
const root = resolve(builder, '../..');
const source = resolve(root, 'external/nxnative');
const pin = '0045c1dfb639f9775891382646ad38c2a11c56bf';
const recipeAtStart = process.env.SWITCHRECOMP_SHADER_CHAIN ? await createRuntimeRecipe({ root, builder, shaderChain: process.env.SWITCHRECOMP_SHADER_CHAIN }) : undefined;
const work = resolve(process.env.SWITCHRECOMP_RUNTIME_WORK ?? resolve(root, 'tmp/odyssey/browser-release/runtime-public'));
if (!work.startsWith(resolve(root, 'tmp/odyssey') + '/')) throw new Error('Runtime build scratch must stay under tmp/odyssey.');
const native = resolve(work, 'src'), output = resolve(work, 'public');
const app = resolve(output, 'files/Super Mario Odyssey.app');
async function run(args: string[], cwd = root, env: Record<string, string | undefined> = {}) {
  const child = Bun.spawn(args, { cwd, env: { ...process.env, ...env }, stdout: 'inherit', stderr: 'inherit' });
  const status = await child.exited;
  if (status) throw new Error(`${args[0]} failed with exit status ${status}.`);
}
await mkdir(work, { recursive: true });
try { await stat(native); throw new Error(`The owned build directory already exists: ${native}. Reuse its completed output or remove this specific scratch directory before rebuilding.`); }
catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
await mkdir(native);
const archive = resolve(work, 'nxnative.tar');
const exportSource = Bun.spawn(['git', '-C', source, 'archive', pin], { stdout: Bun.file(archive), stderr: 'inherit' });
if (await exportSource.exited) throw new Error('Could not export the pinned runtime source.');
await run(['tar', '-xf', archive, '-C', native]);
const patches = ['scripts/patches/nxnative-odyssey-sdk3.patch', 'scripts/patches/nxnative-browser-source-shaders.patch'];
for (const patch of patches) {
  // Stop Git parent discovery: this is an ignored source export inside the root
  // checkout, and git apply would otherwise silently skip its relative paths.
  await run(['git', 'apply', '--check', resolve(root, patch)], native, { GIT_CEILING_DIRECTORIES: work });
  await run(['git', 'apply', resolve(root, patch)], native, { GIT_CEILING_DIRECTORIES: work });
}
for (const name of ['source-shaders.h', 'source-shaders.m']) await copyFile(resolve(builder, 'runtime', name), resolve(native, 'dm/gfx/nvn', name));
await stat(resolve(native, 'dm/host/hle_smo_frame.c'));
const chainHeader = resolve(native, 'dm/gfx/nvn/dmsh_chain.h');
const requestedChain = process.env.SWITCHRECOMP_SHADER_CHAIN;
if (requestedChain) {
  if (!/^[a-z0-9-]{12,40}$/.test(requestedChain)) throw new Error('Invalid browser shader-chain identity.');
  await writeFile(chainHeader, `// Browser toolchain identity; generated by the release build.\n#define DMSH_CHAIN "${requestedChain}"\n`);
}
const shaderChain = /#define DMSH_CHAIN "([a-z0-9-]+)"/.exec(await readFile(chainHeader, 'utf8'))?.[1];
if (!shaderChain) throw new Error('The native runtime has no shader-chain identity.');
const sourceRecipe = recipeAtStart ?? await createRuntimeRecipe({ root, builder, shaderChain });
await run(['make', '-C', resolve(native, 'dm/host'), 'GAME=0100000000010000', '-j4']);
await mkdir(resolve(app, 'Contents/MacOS'), { recursive: true });
await copyFile(resolve(builder, 'runtime/Info.plist'), resolve(app, 'Contents/Info.plist'));
await copyFile(resolve(native, 'dm/host/dmhost'), resolve(app, 'Contents/MacOS/dmhost'));
await run(['xcrun', 'clang', '-arch', 'arm64', '-O2', '-Wall', '-Wextra', '-Werror', '-fobjc-arc', '-framework', 'Cocoa', resolve(builder, 'runtime/launcher.m'), '-o', resolve(app, 'Contents/MacOS/Launcher')]);
for (const executable of ['Launcher', 'dmhost']) {
  const path = resolve(app, 'Contents/MacOS', executable);
  await run(['strip', '-S', path]);
  await run(['codesign', '--force', '--sign', '-', '--identifier', `io.github.switchrecomp.${executable.toLowerCase()}`, path]);
  await run(['codesign', '--verify', '--strict', path]);
  await run(['lipo', path, '-verify_arch', 'arm64']);
}
const fontPackage = resolve(builder, 'node_modules/@fontsource/nunito');
await run(['uv', 'run', '--no-project', resolve(builder, 'runtime/build-fonts.py'), '--nxnative', native, '--font', resolve(fontPackage, 'files/nunito-latin-700-normal.woff2'), '--output', resolve(app, 'Contents/Resources/game/font')]);
const licenses = resolve(app, 'Contents/Resources/Licenses');
await mkdir(licenses, { recursive: true });
for (const [src, name] of [
  [resolve(native, 'LICENSE'), 'nxnative.txt'],
  [resolve(native, 'dm/third_party/libvpx/LICENSE'), 'libvpx.txt'],
  [resolve(native, 'dm/third_party/stb_vorbis/LICENSE'), 'stb-vorbis.txt'],
  [resolve(fontPackage, 'LICENSE'), 'Nunito-OFL.txt'],
]) await copyFile(src!, resolve(licenses, name!));
async function copyVendorNotices(directory: string) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = resolve(directory, entry.name);
    if (entry.isDirectory()) { await copyVendorNotices(full); continue; }
    if (!entry.isFile() || !/^(LICENSE(?:\..+)?|COPYING(?:\..+)?|NOTICE(?:\..+)?|PATENTS)$/i.test(entry.name)) continue;
    const name = relative(resolve(native, 'dm/third_party'), full).replaceAll(/[\\/]/g, '-');
    await copyFile(full, resolve(licenses, name));
  }
}
await copyVendorNotices(resolve(native, 'dm/third_party'));
// Sign only after every public resource exists. Browser conversion extends this
// resource seal for the user's generated game files and rehashes the ad-hoc
// executable's resource slot; code pages remain the signed OSS runtime.
await run(['codesign', '--force', '--sign', '-', '--identifier', 'io.github.switchrecomp.odyssey', app]);
await run(['codesign', '--verify', '--deep', '--strict', app]);
const files: { path: string; url: string; size: number; sha256: string; mode: number }[] = [];
async function visit(directory: string) {
  for (const item of await readdir(directory, { withFileTypes: true })) {
    const full = resolve(directory, item.name);
    if (item.isDirectory()) { await visit(full); continue; }
    if (!item.isFile()) throw new Error('Public runtime templates may contain only ordinary files.');
    const path = relative(resolve(output, 'files'), full).replaceAll('\\', '/');
    const info = await stat(full);
    files.push({ path, url: 'files/' + path.split('/').map(encodeURIComponent).join('/'), size: info.size, sha256: createHash('sha256').update(await readFile(full)).digest('hex'), mode: path.includes('/Contents/MacOS/') ? 0o755 : 0o644 });
  }
}
await visit(app);
const patchHashes = Object.fromEntries(await Promise.all(patches.map(async path => [path, createHash('sha256').update(await readFile(resolve(root, path))).digest('hex')])));
const recipeAtEnd = await createRuntimeRecipe({ root, builder, shaderChain, toolchain: sourceRecipe.inputs.toolchain as Record<string, unknown> });
if (recipeAtEnd.identity !== sourceRecipe.identity) throw new Error('Runtime source recipe changed during the build; no reusable manifest was produced.');
await writeFile(resolve(output, 'manifest.json'), JSON.stringify({ format: 1, kind: 'open-source-runtime-template', architecture: 'arm64', minimumMacOS: '26.0', shaderChain, source: { repository: 'https://github.com/seedds/nxnative', commit: pin, patches: patchHashes }, sourceRecipe, gameAssetsIncluded: false, notarized: false, files }, null, 2) + '\n');
console.log(`Public runtime template ready: ${output}`);
