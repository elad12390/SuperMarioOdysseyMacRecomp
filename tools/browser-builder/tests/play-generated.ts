import assert from 'node:assert/strict';
import { chmod, copyFile, realpath, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { createGameTest } from '../../game-harness/fixture';
import { enterOpeningGameplay } from '../../game-harness/opening';
import { validateTestPath } from '../../game-harness/manager';
import type { NativeState } from '../../game-harness/protocol';
import { assertAudibleAudio } from './audio-levels';

// Only an app mounted/copied from the actual browser-produced DMG is a valid
// input. The caller separately verifies that image and its resource signature.
const argument = process.argv.indexOf('--app');
if (argument < 0 || !process.argv[argument + 1]) throw new Error('Usage: bun tests/play-generated.ts --app PATH');
const app = await realpath(resolve(process.argv[argument + 1]!));
await validateTestPath(app);
assert(app.endsWith('.app'), 'Select the relocated generated app bundle');
const gameRoot = join(app, 'Contents/Resources/game');
const executable = join(app, 'Contents/MacOS/dmhost');
const shell = (value: string) => "'" + value.replaceAll("'", "'\\''") + "'";

process.env.GAME_INSTANCE_ROLE = 'tests';
process.env.GAME_HARNESS_PORT = '4328';
process.env.GAME_HARNESS_RUNTIME = resolve(import.meta.dir, '../../../tmp/odyssey/browser-release/native-test');
process.env.GAME_NATIVE_SOCKET = resolve(import.meta.dir, '../../../tmp/odyssey/browser-release.sock');
const actions = [
  'Boot the app generated by the browser',
  'Reach gameplay with a fresh private save',
  'Walk and prove Mario moves',
  'Jump and land on native controller input',
  'Rotate the native camera',
  'Measure uncapped rendering and preview gameplay',
  'Verify native game audio is audible',
];
const test = await createGameTest('browser-generated-odyssey', {
  title: 'Browser WASM → native Odyssey',
  description: 'Use only the runtime, converted code and data from the browser-produced DMG. Fresh isolated save; prove walking, jumping, camera control, native audio and uncapped rendering.',
  actions, fps: 60,
});
const { game, page } = test;
const evidence: Record<string, unknown> = { app, executable, gameRoot, inputBackend: 'native-unix-socket', windowed: false };
const position = (state: NativeState) => {
  assert(state.timing?.position?.length === 3, 'Native player position must be available');
  return state.timing.position;
};
const ticks = (state: NativeState) => state.timing?.logicTicks ?? 0;
let failure: unknown;
try {
  await test.step(actions[0]!, async () => {
    const wrapper = join(test.artifacts, 'generated-host.command');
    await writeFile(wrapper, [
      '#!/bin/bash', 'set -euo pipefail',
      '[[ "${DM_INSTANCE_LABEL:-}" == Tests && "${DM_AUTOMATED_INPUT:-}" == 1 ]] || exit 2',
      `export DM_ROOT=${shell(gameRoot)}`,
      `export DM_ROMFS=${shell(join(gameRoot, 'extract/v0/RomFS'))}`,
      `export DM_MSL_DIR=${shell(join(gameRoot, 'shader/cache'))}`,
      `export DM_FONT_DIR=${shell(join(gameRoot, 'font'))}`,
      `export DM_NVN_SHMAP=${shell(join(gameRoot, 'profile/0100000000010000/shader_map.tsv'))}`,
      'export DM_MSL_SOURCE=1 DM_AUDIO=1 DM_ARROW_CAMERA=1 DM_LANG=en-US',
      'unset DM_WINDOW DM_FULLSCREEN DM_METAL_HUD DM_KEYS DM_CTL DM_SMO_TAS_MOTION',
      String.raw`printf 'render_fps=0\nshow_fps=1\n' > "$DM_NATIVE_OPTIONS"`,
      `exec ${shell(executable)} ${shell(join(gameRoot, 'patched_v0'))}`, '',
    ].join('\n'));
    await chmod(wrapper, 0o755);
    evidence.started = await game.start({ headless: true, renderFPS: 0, profile: true, nativeHost: wrapper });
  });
  await test.step(actions[1]!, async () => {
    const states: unknown[] = []; evidence.openingStates = states;
    await enterOpeningGameplay(page, { timeout: 180000, onState(state) {
      if (states.length >= 256) states.splice(1, 1); states.push({ atMs: performance.now(), frame: state.frame, generation: state.generation, reads: state.reads, sampling: state.sampling, buttons: state.buttons, consumed: state.consumed, timing: state.timing, ui: state.ui });
    } });
    const state = await page.state();
    assert.equal(state.route?.stage, 'CapWorldHomeStage');
    evidence.opening = state;
    await page.screenshot({ path: join(test.artifacts, 'opening.png') });
  });
  await test.step(actions[2]!, async () => {
    const before = await page.state(), start = position(before);
    await page.keyboard.down('w');
    try { await page.until(async () => ticks(await page.state()) - ticks(before) >= 90, 15000); }
    finally { await page.keyboard.up('w'); }
    const after = await page.state(), end = position(after);
    const distance = Math.hypot(end[0]! - start[0]!, end[2]! - start[2]!);
    assert(distance > 100, `Walking moved Mario only ${distance.toFixed(1)} units`);
    evidence.walk = { before, after, distance };
  });
  await test.step(actions[3]!, async () => {
    const before = await page.state(), ground = position(before)[1]!;
    await page.keyboard.press('k');
    let peak = ground;
    await page.until(async () => {
      const state = await page.state(); peak = Math.max(peak, position(state)[1]!);
      return peak - ground > 30;
    }, 10000);
    await page.until(async () => {
      const state = await page.state(); peak = Math.max(peak, position(state)[1]!);
      return (state.route?.player?.velocity[1] ?? 0) < -1;
    }, 10000);
    await page.until(async () => {
      const state = await page.state();
      return Math.abs(position(state)[1]! - ground) < 3 && /PlayerActorHakoniwaNrvWaitE/.test(state.timing?.playerNerve ?? "") && ticks(state) > ticks(before) + 15;
    }, 15000);
    evidence.jump = { before, after: await page.state(), peak, rise: peak - ground };
  });
  await test.step(actions[4]!, async () => {
    const before = await page.state(), forward = before.route?.cameraForward;
    assert(forward?.length === 3, 'Native camera direction must be available');
    await page.keyboard.down('ArrowRight');
    try {
      await page.until(async () => {
        const state = await page.state(), current = state.route?.cameraForward;
        return ticks(state) - ticks(before) >= 45 && !!current && Math.hypot(...current.map((value, index) => value - forward[index]!)) > 0.15;
      }, 15000);
    } finally { await page.keyboard.up('ArrowRight'); }
    evidence.camera = { before, after: await page.state() };
  });
  await test.step(actions[5]!, async () => {
    const before = await page.state(), started = performance.now();
    await page.until(async () => ticks(await page.state()) - ticks(before) >= 120, 20000);
    const after = await page.state(), seconds = (performance.now() - started) / 1000;
    assert.equal(after.timing?.renderFPS, 0, 'Native rendering must remain uncapped');
    assert(after.frame > before.frame, 'Native renderer did not advance');
    assert.equal(after.timing?.interpolation.restoreMismatches, 0, 'Presentation interpolation must restore native actor state exactly');
    evidence.performance = { seconds, renders: after.frame - before.frame, renderRate: (after.frame - before.frame) / seconds, logicTicks: ticks(after) - ticks(before), before, after };
    await page.screenshot({ path: join(test.artifacts, 'gameplay.png') });
  });
  await test.step(actions[6]!, async () => {
    await game.stop();
    evidence.audio = await assertAudibleAudio(join(test.artifacts, 'native-audio-001.wav'), { lastSeconds: 2 });
  });
} catch (error) { failure = error; }
finally {
  evidence.inputReceipts = page.keyboard.receipts;
  await writeFile(join(test.artifacts, 'generated-app-evidence.json'), JSON.stringify(evidence, null, 2) + '\n');
  try { await test.finish(failure); }
  finally {
    for (const [source, target] of [['frame-times.tsv', 'native-frame-times.tsv'], ['game.log', 'game.log']])
      await copyFile(join(process.env.GAME_HARNESS_RUNTIME!, source!), join(test.artifacts, target!)).catch(() => {});
  }
}
